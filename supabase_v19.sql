  );
$$;

-- 4) 프로필 사진 저장/지우기 --------------------------------------
create or replace function public.friend_set_avatar(p_user text, p_secret text, p_avatar text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  prof public.friend_profiles;
  v text := btrim(coalesce(p_avatar, ''));
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if v <> '' and v !~ '^data:image/(jpeg|jpg|png|webp);base64,' then
    raise exception 'bad_avatar';
  end if;
  if char_length(v) > 200000 then
    raise exception 'avatar_too_big';
  end if;

  update public.friend_profiles
     set avatar_url = nullif(v, ''),
         updated_at = now()
   where user_id = p_user
   returning * into prof;

  if prof.user_id is null then
    raise exception 'unauthorized';
  end if;
  return public._urikkiri_profile_json(prof);
end $$;

-- 5) 그룹 한 개 모양: 사진 · 위치 숨김 · 안 읽음 -------------------
create or replace function public._urikkiri_group_json(p_group text, p_user text)
returns jsonb language sql security definer set search_path = public as $$
  select jsonb_build_object(
    'id', g.id,
    'name', g.name,
    'invite_code', g.invite_code,
    'created_by', g.created_by,
    'created_at', g.created_at,
    'member_count', (select count(*)::int from public.group_members where group_id = g.id),
    'unread', coalesce((
      select count(*)::int
        from public.group_messages m
       where m.group_id = g.id
         and m.sender_id <> p_user
         and m.created_at > coalesce(
           (select gm2.last_read_at from public.group_members gm2
             where gm2.group_id = g.id and gm2.profile_id = p_user),
           (select gm3.joined_at from public.group_members gm3
             where gm3.group_id = g.id and gm3.profile_id = p_user),
           now())
    ), 0),
    'members', coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', pr.user_id,
        'nickname', pr.nickname,
        'emoji', pr.emoji,
        'status_text', pr.status_text,
        'color', pr.color,
        'avatar_url', pr.avatar_url,
        'lat', case when gm.hide_location and pr.user_id <> p_user then null else l.lat end,
        'lng', case when gm.hide_location and pr.user_id <> p_user then null else l.lng end,
        'accuracy', case when gm.hide_location and pr.user_id <> p_user then null else l.accuracy end,
        'battery', case when gm.hide_location and pr.user_id <> p_user then null else l.battery end,
        'charging', case when gm.hide_location and pr.user_id <> p_user then false else l.charging end,
        'speed_kmh', case when gm.hide_location and pr.user_id <> p_user then null else l.speed_kmh end,
        'stay_since', case when gm.hide_location and pr.user_id <> p_user then null else l.stay_since end,
        'updated_at', case when gm.hide_location and pr.user_id <> p_user then null else l.updated_at end,
        'hidden', gm.hide_location,
        'is_me', pr.user_id = p_user,
        'is_friend', exists (
          select 1 from public.friendships f
           where f.status = 'accepted'
             and ((f.requester_id = p_user and f.addressee_id = pr.user_id)
               or (f.addressee_id = p_user and f.requester_id = pr.user_id))
        )
      ) order by (pr.user_id = p_user) desc, pr.nickname)
      from public.group_members gm
      join public.friend_profiles pr on pr.user_id = gm.profile_id
      left join public.friend_locations l on l.user_id = pr.user_id
      where gm.group_id = g.id
    ), '[]'::jsonb),
    'last_message', (
      select jsonb_build_object('body', m.body, 'sender_id', m.sender_id, 'created_at', m.created_at)
        from public.group_messages m
       where m.group_id = g.id
       order by m.created_at desc, m.id desc
       limit 1
    )
  )
  from public.share_groups g
  where g.id = p_group;
$$;

-- 6) 그룹 위치 잠깐 숨기기 / 다시 공개 -----------------------------
create or replace function public.group_toggle_hide(p_user text, p_secret text, p_group text, p_hide boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if not public._urikkiri_in_group(p_user, p_group) then
    raise exception 'not_in_group';
  end if;

  update public.group_members
     set hide_location = coalesce(p_hide, not hide_location)
   where group_id = p_group and profile_id = p_user;

  return jsonb_build_object(
    'group_id', p_group,
    'hidden', (select hide_location from public.group_members where group_id = p_group and profile_id = p_user)
  );
end $$;

