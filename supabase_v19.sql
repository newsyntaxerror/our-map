-- 8) 그룹 동선: 위치를 숨긴 멤버의 좌표는 내려주지 않는다 ----------
create or replace function public.group_history(p_user text, p_secret text, p_group text, p_since timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if not public._urikkiri_in_group(p_user, p_group) then
    raise exception 'not_in_group';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'user_id', h.user_id, 'lat', h.lat, 'lng', h.lng, 'accuracy', h.accuracy,
      'speed_kmh', h.speed_kmh, 'stay_since', h.stay_since, 'recorded_at', h.recorded_at
    ) order by h.recorded_at), '[]'::jsonb)
    into out
  from (
    select * from public.friend_history
     where recorded_at >= coalesce(p_since, now() - interval '24 hours')
       and user_id in (
         select profile_id from public.group_members
          where group_id = p_group
            and (profile_id = p_user or not hide_location)
       )
     order by recorded_at desc
     limit 4000
  ) h;

  return out;
end $$;

create or replace function public.groups_history_since(p_user text, p_secret text, p_since timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'user_id', h.user_id, 'lat', h.lat, 'lng', h.lng, 'accuracy', h.accuracy,
      'speed_kmh', h.speed_kmh, 'stay_since', h.stay_since, 'recorded_at', h.recorded_at
    ) order by h.recorded_at), '[]'::jsonb)
    into out
  from (
    select * from public.friend_history
     where recorded_at >= coalesce(p_since, now() - interval '6 hours')
       and user_id in (
         select gm.profile_id
           from public.group_members gm
           join public.group_members me on me.group_id = gm.group_id
          where me.profile_id = p_user and gm.profile_id <> p_user
       )
       -- 어떤 공유 그룹에서든 위치를 숨긴 사람은 동선도 내려주지 않는다
       and user_id not in (
         select gm.profile_id
           from public.group_members gm
           join public.group_members me on me.group_id = gm.group_id
          where me.profile_id = p_user
            and gm.profile_id <> p_user
            and gm.hide_location
       )
     order by recorded_at desc
     limit 4000
  ) h;

  return out;
end $$;

-- 9) 친구 피드: 프로필 사진 포함 -----------------------------------
create or replace function public.friend_feed(p_user text, p_secret text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare result jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  with pairs as (
    select case when requester_id = p_user then addressee_id else requester_id end as friend_id
    from public.friendships
    where status = 'accepted' and (requester_id = p_user or addressee_id = p_user)
  ),
  unread as (
    select sender_id as friend_id, count(*)::int as n
    from public.friend_messages
    where recipient_id = p_user and read_at is null
    group by sender_id
  ),
  thread_last as (
    select distinct on (case when sender_id = p_user then recipient_id else sender_id end)
      case when sender_id = p_user then recipient_id else sender_id end as friend_id,
      body, created_at, sender_id
    from public.friend_messages
    where sender_id = p_user or recipient_id = p_user
    order by case when sender_id = p_user then recipient_id else sender_id end,
             created_at desc, id desc
  )
  select jsonb_build_object(
    'friends', coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', pr.user_id,
        'nickname', pr.nickname,
        'emoji', pr.emoji,
        'status_text', pr.status_text,
        'color', pr.color,
        'avatar_url', pr.avatar_url,
        'lat', l.lat,
        'lng', l.lng,
        'accuracy', l.accuracy,
        'battery', l.battery,
        'charging', coalesce(l.charging, false),
        'speed_kmh', l.speed_kmh,
        'stay_since', l.stay_since,
        'updated_at', l.updated_at,
        'unread', coalesce(u.n, 0),
        'last_message', lm.body,
        'last_message_at', lm.created_at,
        'last_from_me', (lm.sender_id = p_user)
      ) order by pr.nickname)
      from pairs pa
      join public.friend_profiles pr on pr.user_id = pa.friend_id
      left join public.friend_locations l on l.user_id = pr.user_id
      left join unread u on u.friend_id = pr.user_id
      left join thread_last lm on lm.friend_id = pr.user_id
    ), '[]'::jsonb),
    'incoming', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', f.id, 'user_id', pr.user_id, 'nickname', pr.nickname,
        'emoji', pr.emoji, 'color', pr.color, 'avatar_url', pr.avatar_url, 'created_at', f.created_at
      ) order by f.created_at desc)
      from public.friendships f
      join public.friend_profiles pr on pr.user_id = f.requester_id
      where f.addressee_id = p_user and f.status = 'pending'
    ), '[]'::jsonb),
    'outgoing', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', f.id, 'user_id', pr.user_id, 'nickname', pr.nickname,
        'emoji', pr.emoji, 'color', pr.color, 'avatar_url', pr.avatar_url, 'created_at', f.created_at
      ) order by f.created_at desc)
      from public.friendships f
      join public.friend_profiles pr on pr.user_id = f.addressee_id
      where f.requester_id = p_user and f.status = 'pending'
    ), '[]'::jsonb)
  ) into result;

  return result;
end $$;

-- 10) 이모지 콕 보내기 --------------------------------------------
create or replace function public.poke_send(p_user text, p_secret text, p_to text, p_emoji text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  e text := left(btrim(coalesce(p_emoji, '👋')), 8);
  row public.friend_pokes;
  allowed boolean;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if p_to is null or p_to = '' or p_to = p_user then
    raise exception 'bad_target';
  end if;
  if e = '' then e := '👋'; end if;

  allowed := public._urikkiri_friends(p_user, p_to)
    or exists (
      select 1
        from public.group_members a
        join public.group_members b on b.group_id = a.group_id
       where a.profile_id = p_user and b.profile_id = p_to
    );
  if not allowed then
    raise exception 'not_allowed';
  end if;

  -- 같은 사람에게 3초에 한 번까지만
  if exists (
    select 1 from public.friend_pokes
     where from_id = p_user and to_id = p_to
       and created_at > now() - interval '3 seconds'
  ) then
    raise exception 'too_fast';
  end if;

  insert into public.friend_pokes (from_id, to_id, emoji)
  values (p_user, p_to, e)
  returning * into row;

  return jsonb_build_object(
    'id', row.id, 'from_id', row.from_id, 'to_id', row.to_id,
    'emoji', row.emoji, 'created_at', row.created_at
  );
end $$;

-- 11) 받은 콕 확인 / 확인 표시 -------------------------------------
create or replace function public.poke_poll(p_user text, p_secret text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id', pk.id, 'from_id', pk.from_id, 'emoji', pk.emoji,
      'created_at', pk.created_at, 'nickname', pr.nickname, 'avatar_url', pr.avatar_url
    ) order by pk.created_at), '[]'::jsonb)
    into out
  from public.friend_pokes pk
  join public.friend_profiles pr on pr.user_id = pk.from_id
  where pk.to_id = p_user
    and pk.ack_at is null
    and pk.created_at > now() - interval '10 minutes';

  return out;
end $$;

create or replace function public.poke_ack(p_user text, p_secret text, p_ids bigint[])
returns jsonb language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  update public.friend_pokes
     set ack_at = now()
   where to_id = p_user and ack_at is null
     and id = any(coalesce(p_ids, array[]::bigint[]));
  get diagnostics n = row_count;

  return jsonb_build_object('acked', n);
end $$;

