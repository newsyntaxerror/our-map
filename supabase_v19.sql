-- 우리끼리 — v19: 프로필 사진 · 이모지 콕 · 그룹 위치 숨기기 · 그룹 안 읽음
-- =============================================================
-- · friend_profiles.avatar_url : 프로필 사진(정사각 180px JPEG data URL, 40KB 안팎)
-- · group_members.hide_location : 그룹별 '내 위치 잠깐 숨기기'
-- · group_members.last_read_at  : 그룹 단체 채팅 안 읽음 배지 기준
-- · friend_pokes                : 친구 핀 이모지 콕(찌르기)
-- · 기존 프로필·친구·메시지·동선 데이터는 바꾸지 않습니다.
-- · 여러 번 실행해도 안전합니다.
-- =============================================================

-- 1) 열 추가 -----------------------------------------------------
alter table public.friend_profiles add column if not exists avatar_url text;

alter table public.friend_profiles drop constraint if exists friend_profiles_avatar_check;
alter table public.friend_profiles add constraint friend_profiles_avatar_check
  check (
    avatar_url is null
    or (char_length(avatar_url) between 30 and 200000
        and avatar_url ~ '^data:image/(jpeg|jpg|png|webp);base64,')
  );

alter table public.group_members add column if not exists hide_location boolean not null default false;
alter table public.group_members add column if not exists last_read_at timestamptz;

-- 2) 이모지 콕(찌르기) 표 ----------------------------------------
create table if not exists public.friend_pokes (
  id         bigint generated by default as identity primary key,
  from_id    text not null references public.friend_profiles(user_id) on delete cascade,
  to_id      text not null references public.friend_profiles(user_id) on delete cascade,
  emoji      text not null check (char_length(emoji) between 1 and 8),
  created_at timestamptz not null default now(),
  ack_at     timestamptz
);
create index if not exists friend_pokes_to_idx on public.friend_pokes (to_id, created_at desc);
create index if not exists friend_pokes_from_idx on public.friend_pokes (from_id, created_at desc);

alter table public.friend_pokes enable row level security;
revoke all on public.friend_pokes from anon, authenticated;

