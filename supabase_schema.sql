-- 1) 방 (초대 코드 = 방 이름) -------------------------------------
create table if not exists public.rooms (
  code         text primary key check (char_length(code) between 1 and 20),
  name         text not null default '',
  created_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

-- 2) 방 안의 멤버 현재 위치 -----------------------------------------
create table if not exists public.locations (
  room_code   text not null references public.rooms(code) on delete cascade,
  user_id     text not null,
  nickname    text not null check (char_length(nickname) between 1 and 20),
  emoji       text not null default '🙂',
  status_text text not null default '' check (char_length(status_text) <= 60),
  lat         double precision not null check (lat between -90 and 90),
  lng         double precision not null check (lng between -180 and 180),
  accuracy    double precision,
  battery     smallint check (battery is null or battery between 0 and 100),
  charging    boolean not null default false,
  speed_kmh   double precision,          -- 직전 좌표와의 거리/시간으로 계산한 이동 속도
  stay_since  timestamptz,               -- 같은 장소(약 75m)에 머물기 시작한 시각
  color       text not null default '#0fb9a3',
  updated_at  timestamptz not null default now(),
  primary key (room_code, user_id)
);

-- 이미 만들어 둔 프로젝트용 열 추가 (없을 때만)
alter table public.locations
  add column if not exists speed_kmh  double precision,
  add column if not exists stay_since timestamptz;

-- 고스트 모드(위치 숨김)를 더 이상 쓰지 않습니다.
