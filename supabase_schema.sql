-- 14) 실시간(Realtime) --------------------------------------------
-- 표를 직접 읽을 수 없으므로 postgres_changes 대신
-- 앱이 '새 소식 있음' 신호(broadcast)만 주고받고, 내용은 함수로 다시 받아옵니다.
-- 그래도 혹시 쓰는 경우를 위해 메시지 표를 publication 에 넣어 둡니다.
do $$
declare t text;
begin
  foreach t in array array['friend_messages', 'friend_locations'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
exception
  when undefined_object then
    raise notice 'supabase_realtime publication 이 없습니다. Dashboard → Database → Replication 에서 Realtime 을 켜 주세요.';
  when others then
    raise notice 'Realtime 설정을 건너뛰었습니다: %', sqlerrm;
end $$;

