create index if not exists locations_room_updated_idx
  on public.locations (room_code, updated_at desc);

-- 3) 이동 경로 기록 (동선 · 장소별 머무른 시간) ----------------------
create table if not exists public.location_history (
  id          bigint generated by default as identity primary key,
  room_code   text not null references public.rooms(code) on delete cascade,
  user_id     text not null,
  lat         double precision not null check (lat between -90 and 90),
  lng         double precision not null check (lng between -180 and 180),
  accuracy    double precision,
  speed_kmh   double precision,
  stay_since  timestamptz,
  recorded_at timestamptz not null default now()
);

alter table public.location_history
  add column if not exists speed_kmh  double precision,
  add column if not exists stay_since timestamptz;

-- 같은 방·멤버·시각의 좌표가 두 번 들어가지 않게 (재전송 대비)
create unique index if not exists location_history_point_uidx
  on public.location_history (room_code, user_id, recorded_at);

-- 멤버별 최근 경로 조회용 / 방 전체 최근 24시간 조회용
create index if not exists location_history_member_idx
  on public.location_history (room_code, user_id, recorded_at desc);
create index if not exists location_history_room_idx
  on public.location_history (room_code, recorded_at desc);

-- 4) 접근 권한(RLS) ----------------------------------------------
-- 앱은 로그인 없이 anon key 로 동작합니다.
-- 즉 '방 코드를 아는 사람'이 그 방의 비밀번호를 가진 사람입니다.
-- (아래 7번의 선택 사항을 적용하면 익명 로그인 기반으로 더 좁힐 수 있어요.)
alter table public.rooms            enable row level security;
alter table public.locations        enable row level security;
alter table public.location_history enable row level security;

drop policy if exists rooms_read   on public.rooms;
drop policy if exists rooms_create on public.rooms;
create policy rooms_read   on public.rooms for select to anon, authenticated using (true);
create policy rooms_create on public.rooms for insert to anon, authenticated with check (true);

drop policy if exists locations_read   on public.locations;
drop policy if exists locations_create on public.locations;
drop policy if exists locations_update on public.locations;
drop policy if exists locations_delete on public.locations;
create policy locations_read   on public.locations for select to anon, authenticated using (true);
create policy locations_create on public.locations for insert to anon, authenticated with check (true);
create policy locations_update on public.locations for update to anon, authenticated using (true) with check (true);
create policy locations_delete on public.locations for delete to anon, authenticated using (true);

drop policy if exists history_read   on public.location_history;
drop policy if exists history_create on public.location_history;
drop policy if exists history_delete on public.location_history;
create policy history_read   on public.location_history for select to anon, authenticated using (true);
create policy history_create on public.location_history for insert to anon, authenticated with check (true);
create policy history_delete on public.location_history for delete to anon, authenticated using (true);

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.rooms            to anon, authenticated;
grant select, insert, update, delete on public.locations        to anon, authenticated;
grant select, insert, update, delete on public.location_history to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- 5) 실시간(Realtime) 켜기 ---------------------------------------
-- locations(현재 위치)와 location_history(경로) 변경이 앱으로 즉시 전달됩니다.
do $$
declare
  t text;
begin
  foreach t in array array['locations', 'location_history'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
exception
  when undefined_object then
    raise notice 'supabase_realtime publication 이 없습니다. Dashboard → Database → Replication 에서 Realtime 을 켜 주세요.';
  when others then
    raise notice 'Realtime 설정을 건너뛰었습니다: %', sqlerrm;
end $$;

