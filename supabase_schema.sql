-- =============================================================
-- 우리끼리 (v4) — 친구 요청·수락 기반 위치 공유 + 친구끼리만 1:1 채팅
-- =============================================================
-- · 방(room) 개념을 없애고, '내 프로필 + 고유 친구 코드'로 사람을 맺습니다.
-- · 위치·경로·채팅은 모두 서버 함수(SECURITY DEFINER)를 통해서만 오갑니다.
--   앱은 anon key + 내 비밀 토큰(secret)으로만 동작하고,
--   표에는 직접 접근할 수 없습니다(RLS + 권한 회수).
-- · 여러 번 실행해도 안전합니다(if not exists / create or replace / drop ... if exists).
-- · 기존 v3 표(rooms / locations / location_history)는 그대로 둡니다. 충돌 없음.
-- =============================================================

-- 1) 프로필 ------------------------------------------------------
create table if not exists public.friend_profiles (
  user_id     text primary key check (char_length(user_id) between 8 and 64),
  secret      text not null check (char_length(secret) between 16 and 128),
  nickname    text not null check (char_length(nickname) between 1 and 20),
  friend_code text not null unique check (char_length(friend_code) between 6 and 12),
  emoji       text not null default '🙂' check (char_length(emoji) <= 8),
  status_text text not null default '' check (char_length(status_text) <= 40),
  color       text not null default '#0fb9a3',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- 2) 현재 위치 ----------------------------------------------------
create table if not exists public.friend_locations (
  user_id    text primary key references public.friend_profiles(user_id) on delete cascade,
  lat        double precision not null check (lat between -90 and 90),
  lng        double precision not null check (lng between -180 and 180),
  accuracy   double precision,
  battery    smallint check (battery is null or battery between 0 and 100),
  charging   boolean not null default false,
  speed_kmh  double precision,
  stay_since timestamptz,
  updated_at timestamptz not null default now()
);

-- 3) 이동 경로 기록 (동선 · 머문 시간 타임라인) ----------------------
create table if not exists public.friend_history (
  id          bigint generated by default as identity primary key,
  user_id     text not null references public.friend_profiles(user_id) on delete cascade,
  lat         double precision not null check (lat between -90 and 90),
  lng         double precision not null check (lng between -180 and 180),
  accuracy    double precision,
  speed_kmh   double precision,
  stay_since  timestamptz,
  recorded_at timestamptz not null default now()
);

create unique index if not exists friend_history_point_uidx
  on public.friend_history (user_id, recorded_at);
create index if not exists friend_history_user_idx
  on public.friend_history (user_id, recorded_at desc);

-- 4) 친구 관계 ----------------------------------------------------
-- status: pending(요청 보냄) / accepted(서로 친구) / declined(거절)
create table if not exists public.friendships (
  id           bigint generated by default as identity primary key,
  requester_id text not null references public.friend_profiles(user_id) on delete cascade,
  addressee_id text not null references public.friend_profiles(user_id) on delete cascade,
  status       text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at   timestamptz not null default now(),
  responded_at timestamptz,
  check (requester_id <> addressee_id)
);

-- 한 쌍은 한 줄만 (방향과 무관하게)
create unique index if not exists friendships_pair_uidx
  on public.friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));
create index if not exists friendships_requester_idx on public.friendships (requester_id, status);
create index if not exists friendships_addressee_idx on public.friendships (addressee_id, status);

-- 5) 친구끼리만 주고받는 1:1 메시지 --------------------------------
create table if not exists public.friend_messages (
  id           bigint generated by default as identity primary key,
  sender_id    text not null references public.friend_profiles(user_id) on delete cascade,
  recipient_id text not null references public.friend_profiles(user_id) on delete cascade,
  body         text not null check (char_length(body) between 1 and 1000),
  created_at   timestamptz not null default now(),
  read_at      timestamptz
);

create index if not exists friend_messages_thread_idx
  on public.friend_messages (sender_id, recipient_id, created_at desc);
create index if not exists friend_messages_inbox_idx
  on public.friend_messages (recipient_id, read_at, created_at desc);

-- 6) 도우미 함수 --------------------------------------------------
create or replace function public._urikkiri_color(p_id text)
returns text language sql immutable as $$
  select (array['#0fb9a3','#f59e0b','#6366f1','#ec4899','#8b5cf6','#0ea5e9','#ef4444','#14b8a6'])
         [1 + (abs(hashtext(coalesce(p_id, ''))) % 8)];
$$;

create or replace function public._urikkiri_code(p_nick text)
returns text language plpgsql as $$
declare
  alphabet text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  prefix   text := '';
  code     text;
  i        int;
  tries    int := 0;
begin
  if coalesce(p_nick, '') ~ '[A-Za-z0-9]' then
    prefix := upper(regexp_replace(p_nick, '[^A-Za-z0-9]', '', 'g'));
    prefix := substr(prefix, 1, 3);
  end if;
  while char_length(prefix) < 3 loop
    prefix := prefix || substr(alphabet, 1 + floor(random() * char_length(alphabet))::int, 1);
  end loop;

  loop
    code := prefix || '-';
    for i in 1..4 loop
      code := code || substr(alphabet, 1 + floor(random() * char_length(alphabet))::int, 1);
    end loop;
    exit when not exists (select 1 from public.friend_profiles where friend_code = code);
    tries := tries + 1;
    if tries >= 40 then
      code := 'URI-' || lpad((floor(random() * 90000) + 10000)::int::text, 5, '0');
      exit when not exists (select 1 from public.friend_profiles where friend_code = code);
      exit;
    end if;
  end loop;
  return code;
end $$;

create or replace function public._urikkiri_ok(p_user text, p_secret text)
returns boolean language sql security definer set search_path = public as $$
  select exists (
    select 1 from public.friend_profiles
    where user_id = p_user and secret = p_secret
  );
$$;

create or replace function public._urikkiri_friends(a text, b text)
returns boolean language sql security definer set search_path = public as $$
  select exists (
    select 1 from public.friendships
    where status = 'accepted'
      and ((requester_id = a and addressee_id = b) or (requester_id = b and addressee_id = a))
  );
$$;

create or replace function public._urikkiri_profile_json(p public.friend_profiles)
returns jsonb language sql immutable as $$
  select jsonb_build_object(
    'user_id', p.user_id,
    'friend_code', p.friend_code,
    'nickname', p.nickname,
    'emoji', p.emoji,
    'status_text', p.status_text,
    'color', p.color,
    'created_at', p.created_at
  );
$$;

-- 7) 프로필: 처음 등록 / 복원 / 수정 --------------------------------
create or replace function public.friend_bootstrap(p_user text, p_secret text, p_nickname text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  prof public.friend_profiles;
  nick text := left(btrim(coalesce(p_nickname, '')), 12);
begin
  if p_user is null or char_length(p_user) < 8 or p_secret is null or char_length(p_secret) < 16 then
    raise exception 'invalid_credentials';
  end if;

  select * into prof from public.friend_profiles where user_id = p_user;

  if prof.user_id is not null then
    if prof.secret <> p_secret then
      raise exception 'unauthorized';
    end if;
    if nick <> '' and nick <> prof.nickname then
      update public.friend_profiles
         set nickname = nick, updated_at = now()
       where user_id = p_user
       returning * into prof;
    end if;
    return public._urikkiri_profile_json(prof);
  end if;

  if nick = '' then nick := '친구'; end if;

  insert into public.friend_profiles (user_id, secret, nickname, friend_code, color)
  values (p_user, p_secret, nick, public._urikkiri_code(nick), public._urikkiri_color(p_user))
  returning * into prof;

  return public._urikkiri_profile_json(prof);
end $$;

create or replace function public.friend_me(p_user text, p_secret text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare prof public.friend_profiles;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  select * into prof from public.friend_profiles where user_id = p_user;
  return public._urikkiri_profile_json(prof);
end $$;

create or replace function public.friend_update_profile(
  p_user text, p_secret text, p_nickname text, p_emoji text, p_status text
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  prof public.friend_profiles;
  nick text := left(btrim(coalesce(p_nickname, '')), 12);
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  update public.friend_profiles
     set nickname    = case when nick <> '' then nick else nickname end,
         emoji       = coalesce(nullif(left(coalesce(p_emoji, ''), 8), ''), emoji),
         status_text = left(coalesce(p_status, status_text), 40),
         updated_at  = now()
   where user_id = p_user
   returning * into prof;
  return public._urikkiri_profile_json(prof);
end $$;

-- 8) 위치 · 경로 ---------------------------------------------------
create or replace function public.friend_publish(
  p_user text, p_secret text,
  p_lat double precision, p_lng double precision,
  p_accuracy double precision default null,
  p_battery smallint default null,
  p_charging boolean default false,
  p_speed_kmh double precision default null,
  p_stay_since timestamptz default null
) returns void language plpgsql security definer set search_path = public as $$
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  insert into public.friend_locations
    (user_id, lat, lng, accuracy, battery, charging, speed_kmh, stay_since, updated_at)
  values
    (p_user, p_lat, p_lng, p_accuracy,
     case when p_battery is null then null else greatest(0, least(100, p_battery)) end,
     coalesce(p_charging, false), p_speed_kmh, p_stay_since, now())
  on conflict (user_id) do update
    set lat = excluded.lat,
        lng = excluded.lng,
        accuracy = excluded.accuracy,
        battery = excluded.battery,
        charging = excluded.charging,
        speed_kmh = excluded.speed_kmh,
        stay_since = excluded.stay_since,
        updated_at = excluded.updated_at;
end $$;

create or replace function public.friend_log_point(
  p_user text, p_secret text,
  p_lat double precision, p_lng double precision,
  p_accuracy double precision default null,
  p_speed_kmh double precision default null,
  p_stay_since timestamptz default null,
  p_recorded_at timestamptz default null
) returns void language plpgsql security definer set search_path = public as $$
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  insert into public.friend_history
    (user_id, lat, lng, accuracy, speed_kmh, stay_since, recorded_at)
  values
    (p_user, p_lat, p_lng, p_accuracy, p_speed_kmh, p_stay_since,
     coalesce(p_recorded_at, now()))
  on conflict (user_id, recorded_at) do nothing;
end $$;

-- 9) 친구 피드: 친구 목록·위치·안 읽은 메시지·요청 목록 --------------
create or replace function public.friend_feed(p_user text, p_secret text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare result jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  with pairs as (
    select case when requester_id = p_user then addressee_id else requester_id end as friend_id
    from public.friendships
    where status = 'accepted' and (requester_id = p_user or addressee_id = p_user)
  ),
  unread as (
    select sender_id as friend_id, count(*)::int as n
    from public.friend_messages
    where recipient_id = p_user and read_at is null
    group by sender_id
  ),
  thread_last as (
    select distinct on (case when sender_id = p_user then recipient_id else sender_id end)
      case when sender_id = p_user then recipient_id else sender_id end as friend_id,
      body, created_at, sender_id
    from public.friend_messages
    where sender_id = p_user or recipient_id = p_user
    order by case when sender_id = p_user then recipient_id else sender_id end,
             created_at desc, id desc
  )
  select jsonb_build_object(
    'friends', coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', pr.user_id,
        'nickname', pr.nickname,
        'emoji', pr.emoji,
        'status_text', pr.status_text,
        'color', pr.color,
        'lat', l.lat,
        'lng', l.lng,
        'accuracy', l.accuracy,
        'battery', l.battery,
        'charging', coalesce(l.charging, false),
        'speed_kmh', l.speed_kmh,
        'stay_since', l.stay_since,
        'updated_at', l.updated_at,
        'unread', coalesce(u.n, 0),
        'last_message', lm.body,
        'last_message_at', lm.created_at,
        'last_from_me', (lm.sender_id = p_user)
      ) order by pr.nickname)
      from pairs pa
      join public.friend_profiles pr on pr.user_id = pa.friend_id
      left join public.friend_locations l on l.user_id = pr.user_id
      left join unread u on u.friend_id = pr.user_id
      left join thread_last lm on lm.friend_id = pr.user_id
    ), '[]'::jsonb),
    'incoming', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', f.id, 'user_id', pr.user_id, 'nickname', pr.nickname,
        'emoji', pr.emoji, 'color', pr.color, 'created_at', f.created_at
      ) order by f.created_at desc)
      from public.friendships f
      join public.friend_profiles pr on pr.user_id = f.requester_id
      where f.addressee_id = p_user and f.status = 'pending'
    ), '[]'::jsonb),
    'outgoing', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', f.id, 'user_id', pr.user_id, 'nickname', pr.nickname,
        'emoji', pr.emoji, 'color', pr.color, 'created_at', f.created_at
      ) order by f.created_at desc)
      from public.friendships f
      join public.friend_profiles pr on pr.user_id = f.addressee_id
      where f.requester_id = p_user and f.status = 'pending'
    ), '[]'::jsonb)
  ) into result;

  return result;
end $$;

-- 10) 친구 요청 · 수락 · 거절 · 끊기 --------------------------------
create or replace function public.friend_request(p_user text, p_secret text, p_code text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  target public.friend_profiles;
  f public.friendships;
  code text := upper(regexp_replace(coalesce(p_code, ''), '\s', '', 'g'));
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if code = '' then
    return jsonb_build_object('status', 'not_found');
  end if;

  select * into target from public.friend_profiles where friend_code = code;
  if target.user_id is null then
    return jsonb_build_object('status', 'not_found');
  end if;
  if target.user_id = p_user then
    return jsonb_build_object('status', 'self');
  end if;

  select * into f from public.friendships
   where (requester_id = p_user and addressee_id = target.user_id)
      or (requester_id = target.user_id and addressee_id = p_user)
   limit 1;

  if f.id is not null then
    if f.status = 'accepted' then
      return jsonb_build_object('status', 'already_friends',
        'user_id', target.user_id, 'nickname', target.nickname);
    end if;
    if f.status = 'pending' and f.requester_id = p_user then
      return jsonb_build_object('status', 'already_requested',
        'user_id', target.user_id, 'nickname', target.nickname);
    end if;
    if f.status = 'pending' and f.requester_id = target.user_id then
      -- 서로 요청하면 바로 친구가 된다
      update public.friendships set status = 'accepted', responded_at = now() where id = f.id;
      return jsonb_build_object('status', 'accepted',
        'user_id', target.user_id, 'nickname', target.nickname);
    end if;
    -- 거절했던 상대에게 다시 요청
    update public.friendships
       set requester_id = p_user, addressee_id = target.user_id,
           status = 'pending', created_at = now(), responded_at = null
     where id = f.id;
    return jsonb_build_object('status', 'sent',
      'user_id', target.user_id, 'nickname', target.nickname);
  end if;

  insert into public.friendships (requester_id, addressee_id, status)
  values (p_user, target.user_id, 'pending');

  return jsonb_build_object('status', 'sent',
    'user_id', target.user_id, 'nickname', target.nickname);
end $$;

create or replace function public.friend_respond(p_user text, p_secret text, p_id bigint, p_accept boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare f public.friendships;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  update public.friendships
     set status = case when p_accept then 'accepted' else 'declined' end,
         responded_at = now()
   where id = p_id and addressee_id = p_user and status = 'pending'
   returning * into f;

  if f.id is null then
    return jsonb_build_object('status', 'not_found');
  end if;
  return jsonb_build_object('status', f.status);
end $$;

create or replace function public.friend_remove(p_user text, p_secret text, p_friend text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  delete from public.friendships
   where (requester_id = p_user and addressee_id = p_friend)
      or (requester_id = p_friend and addressee_id = p_user);
  get diagnostics n = row_count;

  -- 친구를 끊으면 대화도 함께 정리한다
  delete from public.friend_messages
   where (sender_id = p_user and recipient_id = p_friend)
      or (sender_id = p_friend and recipient_id = p_user);

  return jsonb_build_object('removed', n);
end $$;

-- 11) 이동 기록 조회 ------------------------------------------------
create or replace function public.friend_history(
  p_user text, p_secret text, p_friend text, p_since timestamptz default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  target text := coalesce(nullif(p_friend, ''), p_user);
  out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if target <> p_user and not public._urikkiri_friends(p_user, target) then
    raise exception 'not_friends';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'lat', h.lat, 'lng', h.lng, 'accuracy', h.accuracy,
      'speed_kmh', h.speed_kmh, 'stay_since', h.stay_since, 'recorded_at', h.recorded_at
    ) order by h.recorded_at), '[]'::jsonb)
    into out
  from (
    select * from public.friend_history
     where user_id = target
       and recorded_at >= coalesce(p_since, now() - interval '24 hours')
     order by recorded_at desc
     limit 600
  ) h;

  return out;
end $$;

create or replace function public.friends_history_since(
  p_user text, p_secret text, p_since timestamptz default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'user_id', h.user_id, 'lat', h.lat, 'lng', h.lng, 'accuracy', h.accuracy,
      'speed_kmh', h.speed_kmh, 'stay_since', h.stay_since, 'recorded_at', h.recorded_at
    ) order by h.recorded_at), '[]'::jsonb)
    into out
  from (
    select * from public.friend_history
     where recorded_at >= coalesce(p_since, now() - interval '24 hours')
       and (user_id = p_user or public._urikkiri_friends(p_user, user_id))
     order by recorded_at desc
     limit 3000
  ) h;

  return out;
end $$;

-- 12) 채팅: 보내기 · 읽기 · 안 읽음 표시 ----------------------------
create or replace function public.friend_send_message(
  p_user text, p_secret text, p_to text, p_body text
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  msg public.friend_messages;
  body text := btrim(coalesce(p_body, ''));
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if body = '' then
    raise exception 'empty_message';
  end if;
  if not public._urikkiri_friends(p_user, p_to) then
    raise exception 'not_friends';
  end if;

  insert into public.friend_messages (sender_id, recipient_id, body)
  values (p_user, p_to, left(body, 1000))
  returning * into msg;

  return jsonb_build_object(
    'id', msg.id, 'sender_id', msg.sender_id, 'recipient_id', msg.recipient_id,
    'body', msg.body, 'created_at', msg.created_at, 'read_at', msg.read_at
  );
end $$;

create or replace function public.friend_messages(
  p_user text, p_secret text, p_friend text, p_since timestamptz default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if not public._urikkiri_friends(p_user, p_friend) then
    raise exception 'not_friends';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id', m.id, 'sender_id', m.sender_id, 'recipient_id', m.recipient_id,
      'body', m.body, 'created_at', m.created_at, 'read_at', m.read_at
    ) order by m.created_at, m.id), '[]'::jsonb)
    into out
  from (
    select * from public.friend_messages
     where ((sender_id = p_user and recipient_id = p_friend)
         or (sender_id = p_friend and recipient_id = p_user))
       and (p_since is null or created_at > p_since)
     order by created_at desc, id desc
     limit 300
  ) m;

  return out;
end $$;

create or replace function public.friend_mark_read(p_user text, p_secret text, p_friend text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  update public.friend_messages
     set read_at = now()
   where recipient_id = p_user and sender_id = p_friend and read_at is null;
  get diagnostics n = row_count;

  return jsonb_build_object('read', n);
end $$;

