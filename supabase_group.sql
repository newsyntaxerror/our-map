-- =============================================================
-- 우리끼리 — 그룹 위치 공유 · 그룹 채팅
-- =============================================================
-- · 그룹에 들어가면 서로 1:1 친구가 아니어도 그룹 멤버끼리
--   위치·배터리·체류 상태·이동 동선을 볼 수 있습니다.
-- · 그룹 밖 사람에게는 보이지 않습니다(서버 함수가 멤버 여부를 확인).
-- · 기존 friend_profiles / friendships / friend_messages / friend_history 는 건드리지 않습니다.
-- · 여러 번 실행해도 안전합니다.
-- =============================================================

-- 1) 표 ---------------------------------------------------------
create table if not exists public.share_groups (
  id          text primary key check (char_length(id) between 8 and 64),
  name        text not null check (char_length(name) between 1 and 30),
  invite_code text not null unique check (char_length(invite_code) between 6 and 12),
  created_by  text not null references public.friend_profiles(user_id) on delete cascade,
  created_at  timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id   text not null references public.share_groups(id) on delete cascade,
  profile_id text not null references public.friend_profiles(user_id) on delete cascade,
  joined_at  timestamptz not null default now(),
  primary key (group_id, profile_id)
);
create index if not exists group_members_profile_idx on public.group_members (profile_id);

create table if not exists public.group_messages (
  id         bigint generated by default as identity primary key,
  group_id   text not null references public.share_groups(id) on delete cascade,
  sender_id  text not null references public.friend_profiles(user_id) on delete cascade,
  body       text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);
create index if not exists group_messages_group_idx on public.group_messages (group_id, created_at desc);

alter table public.share_groups   enable row level security;
alter table public.group_members  enable row level security;
alter table public.group_messages enable row level security;
revoke all on public.share_groups   from anon, authenticated;
revoke all on public.group_members  from anon, authenticated;
revoke all on public.group_messages from anon, authenticated;

-- 2) 도우미 ------------------------------------------------------
create or replace function public._urikkiri_group_code()
returns text language sql volatile as $$
  select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789',
                           1 + floor(random() * 32)::int, 1), '')
    from generate_series(1, 6);
$$;

create or replace function public._urikkiri_in_group(p_user text, p_group text)
returns boolean language sql security definer set search_path = public as $$
  select exists (
    select 1 from public.group_members
     where group_id = p_group and profile_id = p_user
  );
$$;

-- 그룹 한 개를 앱이 쓰는 모양으로 (멤버 위치·친구 여부 포함)
create or replace function public._urikkiri_group_json(p_group text, p_user text)
returns jsonb language sql security definer set search_path = public as $$
  select jsonb_build_object(
    'id', g.id,
    'name', g.name,
    'invite_code', g.invite_code,
    'created_by', g.created_by,
    'created_at', g.created_at,
    'member_count', (select count(*)::int from public.group_members where group_id = g.id),
    'members', coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', pr.user_id,
        'nickname', pr.nickname,
        'emoji', pr.emoji,
        'status_text', pr.status_text,
        'color', pr.color,
        'lat', l.lat,
        'lng', l.lng,
        'accuracy', l.accuracy,
        'battery', l.battery,
        'charging', l.charging,
        'speed_kmh', l.speed_kmh,
        'stay_since', l.stay_since,
        'updated_at', l.updated_at,
        'is_me', pr.user_id = p_user,
        'is_friend', exists (
          select 1 from public.friendships f
           where f.status = 'accepted'
             and ((f.requester_id = p_user and f.addressee_id = pr.user_id)
               or (f.addressee_id = p_user and f.requester_id = pr.user_id))
        )
      ) order by (pr.user_id = p_user) desc, pr.nickname)
      from public.group_members gm
      join public.friend_profiles pr on pr.user_id = gm.profile_id
      left join public.friend_locations l on l.user_id = pr.user_id
      where gm.group_id = g.id
    ), '[]'::jsonb),
    'last_message', (
      select jsonb_build_object('body', m.body, 'sender_id', m.sender_id, 'created_at', m.created_at)
        from public.group_messages m
       where m.group_id = g.id
       order by m.created_at desc, m.id desc
       limit 1
    )
  )
  from public.share_groups g
  where g.id = p_group;
$$;

-- 3) 그룹 만들기 --------------------------------------------------
create or replace function public.group_create(p_user text, p_secret text, p_name text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  gname text := left(btrim(coalesce(p_name, '')), 30);
  gid   text := 'g-' || replace(gen_random_uuid()::text, '-', '');
  code  text;
  tries int := 0;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if gname = '' then gname := '우리 그룹'; end if;

  loop
    tries := tries + 1;
    code := public._urikkiri_group_code();
    begin
      insert into public.share_groups (id, name, invite_code, created_by)
      values (gid, gname, code, p_user);
      exit;
    exception when unique_violation then
      if tries >= 6 then raise; end if;
    end;
  end loop;

  insert into public.group_members (group_id, profile_id) values (gid, p_user)
  on conflict do nothing;

  return public._urikkiri_group_json(gid, p_user);
end $$;

-- 4) 초대 코드로 참여 ---------------------------------------------
create or replace function public.group_join(p_user text, p_secret text, p_code text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  g public.share_groups;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  select * into g from public.share_groups
   where upper(invite_code) = upper(btrim(coalesce(p_code, '')));
  if g.id is null then
    raise exception 'not_found';
  end if;

  insert into public.group_members (group_id, profile_id) values (g.id, p_user)
  on conflict do nothing;

  return public._urikkiri_group_json(g.id, p_user);
end $$;

-- 5) 나가기 -------------------------------------------------------
create or replace function public.group_leave(p_user text, p_secret text, p_group text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  g public.share_groups;
  left_count int;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  delete from public.group_members where group_id = p_group and profile_id = p_user;

  select count(*) into left_count from public.group_members where group_id = p_group;
  if left_count = 0 then
    delete from public.share_groups where id = p_group;
  end if;

  return jsonb_build_object('left', true, 'group_id', p_group);
end $$;

-- 6) 내 그룹 목록 (멤버 위치·최근 대화) -----------------------------
create or replace function public.group_feed(p_user text, p_secret text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  select coalesce(jsonb_agg(public._urikkiri_group_json(g.id, p_user) order by g.created_at), '[]'::jsonb)
    into out
  from public.share_groups g
  join public.group_members gm on gm.group_id = g.id
  where gm.profile_id = p_user;

  return out;
end $$;

-- 7) 그룹 메시지 --------------------------------------------------
create or replace function public.group_send_message(p_user text, p_secret text, p_group text, p_body text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  msg public.group_messages;
  body text := btrim(coalesce(p_body, ''));
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if not public._urikkiri_in_group(p_user, p_group) then
    raise exception 'not_in_group';
  end if;
  if body = '' then
    raise exception 'empty_message';
  end if;

  insert into public.group_messages (group_id, sender_id, body)
  values (p_group, p_user, left(body, 1000))
  returning * into msg;

  return jsonb_build_object(
    'id', msg.id, 'group_id', msg.group_id, 'sender_id', msg.sender_id,
    'body', msg.body, 'created_at', msg.created_at
  );
end $$;

create or replace function public.group_messages(p_user text, p_secret text, p_group text, p_since timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if not public._urikkiri_in_group(p_user, p_group) then
    raise exception 'not_in_group';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'id', m.id, 'group_id', m.group_id, 'sender_id', m.sender_id,
      'body', m.body, 'created_at', m.created_at
    ) order by m.created_at), '[]'::jsonb)
    into out
  from (
    select * from public.group_messages
     where group_id = p_group
       and created_at >= coalesce(p_since, now() - interval '7 days')
     order by created_at desc, id desc
     limit 300
  ) m;

  return out;
end $$;

-- 8) 그룹 멤버의 이동 기록 ----------------------------------------
create or replace function public.group_history(p_user text, p_secret text, p_group text, p_since timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;
  if not public._urikkiri_in_group(p_user, p_group) then
    raise exception 'not_in_group';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'user_id', h.user_id, 'lat', h.lat, 'lng', h.lng, 'accuracy', h.accuracy,
      'speed_kmh', h.speed_kmh, 'stay_since', h.stay_since, 'recorded_at', h.recorded_at
    ) order by h.recorded_at), '[]'::jsonb)
    into out
  from (
    select * from public.friend_history
     where recorded_at >= coalesce(p_since, now() - interval '24 hours')
       and user_id in (select profile_id from public.group_members where group_id = p_group)
     order by recorded_at desc
     limit 4000
  ) h;

  return out;
end $$;

-- 내 모든 그룹 멤버의 기록(지도 실시간 동선용)
create or replace function public.groups_history_since(p_user text, p_secret text, p_since timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._urikkiri_ok(p_user, p_secret) then
    raise exception 'unauthorized';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'user_id', h.user_id, 'lat', h.lat, 'lng', h.lng, 'accuracy', h.accuracy,
      'speed_kmh', h.speed_kmh, 'stay_since', h.stay_since, 'recorded_at', h.recorded_at
    ) order by h.recorded_at), '[]'::jsonb)
    into out
  from (
    select * from public.friend_history
     where recorded_at >= coalesce(p_since, now() - interval '6 hours')
       and user_id in (
         select gm.profile_id
           from public.group_members gm
           join public.group_members me on me.group_id = gm.group_id
          where me.profile_id = p_user and gm.profile_id <> p_user
       )
     order by recorded_at desc
     limit 4000
  ) h;

  return out;
end $$;

-- 9) 초대 링크 미리보기 (로그인 전) ---------------------------------
create or replace function public.group_invite_info(p_code text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare g public.share_groups; n int;
begin
  select * into g from public.share_groups
   where upper(invite_code) = upper(btrim(coalesce(p_code, '')));
  if g.id is null then
    return jsonb_build_object('ok', false);
  end if;
  select count(*)::int into n from public.group_members where group_id = g.id;
  return jsonb_build_object('ok', true, 'name', g.name, 'member_count', n);
end $$;

